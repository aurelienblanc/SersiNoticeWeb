// Lucide is a development dependency only. Django serves the generated SVGs.
const fs = require('node:fs');
const path = require('node:path');
const lucide = require('lucide');

const names = {
  'folder-open': 'FolderOpen',
  'folder-archive': 'FolderArchive',
  'file-text': 'FileText',
  'file-search': 'FileSearch',
  'layout-dashboard': 'LayoutDashboard',
  package: 'Package',
  history: 'History',
  search: 'Search',
  eye: 'Eye',
  download: 'Download',
  plus: 'Plus',
  save: 'Save',
  'log-out': 'LogOut',
  'log-in': 'LogIn',
  'key-round': 'KeyRound',
  settings: 'Settings',
  'database-backup': 'DatabaseBackup',
  'shield-check': 'ShieldCheck',
  'rotate-ccw': 'RotateCcw',
  upload: 'Upload',
  'refresh-cw': 'RefreshCw',
  list: 'List',
  'folder-tree': 'FolderTree',
  'list-x': 'ListX',
  'arrow-left': 'ArrowLeft',
  'arrow-right': 'ArrowRight',
  'arrow-up-right': 'ArrowUpRight',
  info: 'Info',
  'circle-check': 'CircleCheck',
  check: 'Check',
  'file-plus': 'FilePlus',
  'square-pen': 'SquarePen',
  'trash-2': 'Trash2',
  'scroll-text': 'ScrollText',
  filter: 'Filter',
  factory: 'Factory',
  layers: 'Layers',
  network: 'Network',
  files: 'Files',
  'list-checks': 'ListChecks',
};

const packageRoot = path.resolve(path.dirname(require.resolve('lucide')), '../..');
const { version } = JSON.parse(fs.readFileSync(path.join(packageRoot, 'package.json'), 'utf8'));
const output = path.resolve(__dirname, '../static/icons/lucide');
const notice = `<!-- Lucide ${version}; ISC and Feather MIT licenses: see LICENSE. Generated by tools/build-icons.cjs. -->\n`;
const attributes =
  'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"';
const escape = (value) =>
  String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
const files = new Map();
const symbols = [];

for (const [name, exportName] of Object.entries(names)) {
  const nodes = lucide.icons?.[exportName] ?? lucide[exportName];
  if (!nodes) throw new Error(`Missing Lucide icon: ${exportName}`);
  const shapes = nodes
    .map(([tag, attrs]) => {
      const serialized = Object.entries(attrs)
        .filter(([key]) => key !== 'key')
        .map(([key, value]) => `${key}="${escape(value)}"`)
        .join(' ');
      return `  <${tag} ${serialized} />`;
    })
    .join('\n');
  symbols.push(`<symbol id="${name}" ${attributes}>\n${shapes}\n</symbol>`);
  files.set(
    `${name}.svg`,
    `${notice}<svg xmlns="http://www.w3.org/2000/svg" ${attributes}>\n${shapes}\n</svg>\n`,
  );
  if (name === 'trash-2') {
    files.set(
      'trash-2-white.svg',
      `${notice}<svg xmlns="http://www.w3.org/2000/svg" ${attributes.replace('currentColor', '#ffffff')}>\n${shapes}\n</svg>\n`,
    );
  }
}
files.set(
  'sprite.svg',
  `${notice}<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`,
);
files.set(
  'LICENSE',
  fs.readFileSync(path.join(packageRoot, 'LICENSE'), 'utf8').replaceAll('\r\n', '\n'),
);

if (process.argv.includes('--check')) {
  for (const [name, contents] of files) {
    const target = path.join(output, name);
    if (
      !fs.existsSync(target) ||
      fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== contents
    ) {
      throw new Error(`Regenerate icons with pnpm run icons:build (${name}).`);
    }
  }
  console.log(`Lucide ${version}: generated assets are up to date.`);
} else {
  fs.mkdirSync(output, { recursive: true });
  for (const [name, contents] of files) fs.writeFileSync(path.join(output, name), contents);
  console.log(`Generated ${Object.keys(names).length} Lucide ${version} icons and their licenses.`);
}
